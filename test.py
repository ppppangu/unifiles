#!/usr/bin/env python3
"""
Simple test script for the upload_minio endpoint
Tests the file upload functionality on port 8000
"""

import requests
import json
from pathlib import Path
import io

# Server configuration
SERVER_URL = "http://localhost:8000"
UPLOAD_ENDPOINT = f"{SERVER_URL}/upload_minio"
HEALTH_ENDPOINT = f"{SERVER_URL}/health"

def test_health_check():
    """Test if the server is running"""
    print("🔍 Testing server health...")
    try:
        response = requests.get(HEALTH_ENDPOINT, timeout=5)
        if response.status_code == 200:
            print("✅ Server is running and healthy")
            return True
        else:
            print(f"❌ Server health check failed: {response.status_code}")
            return False
    except requests.exceptions.RequestException as e:
        print(f"❌ Cannot connect to server: {e}")
        return False

def create_test_file():
    """Create a simple test file for upload"""
    test_content = b"This is a test file for upload_minio endpoint testing.\nGenerated by test.py script."
    return test_content, "test_file.txt"

def test_upload_with_user_id(user_id="test_user"):
    """Test file upload with specific user_id"""
    print(f"\n📤 Testing upload with user_id: {user_id}")

    # Create test file
    file_content, filename = create_test_file()

    # Prepare form data
    files = {
        'upload_file': (filename, io.BytesIO(file_content), 'text/plain')
    }
    data = {
        'user_id': user_id
    }

    try:
        response = requests.post(UPLOAD_ENDPOINT, files=files, data=data, timeout=30)

        print(f"Status Code: {response.status_code}")
        print(f"Response: {json.dumps(response.json(), indent=2)}")

        if response.status_code == 200:
            result = response.json()
            if result.get("status") == "success":
                print("✅ Upload successful!")
                data = result.get("data", {})
                print(f"   File ID: {data.get('file_id')}")
                print(f"   Public URL: {data.get('public_url')}")
                print(f"   File Size: {data.get('file_size')} bytes")
                return True
            else:
                print(f"❌ Upload failed: {result.get('message')}")
                return False
        else:
            print(f"❌ Upload failed with status code: {response.status_code}")
            return False

    except requests.exceptions.RequestException as e:
        print(f"❌ Request failed: {e}")
        return False

