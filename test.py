def test_upload_no_file():
    """Test upload without file (should fail)"""
    print(f"\n📤 Testing upload without file (should fail)")

    data = {
        'user_id': 'test_user'
    }

    try:
        response = requests.post(UPLOAD_ENDPOINT, data=data, timeout=30)

        print(f"Status Code: {response.status_code}")
        print(f"Response: {json.dumps(response.json(), indent=2)}")

        if response.status_code == 400:
            print("✅ Correctly rejected upload without file")
            return True
        else:
            print(f"❌ Expected 400 status code, got: {response.status_code}")
            return False

    except requests.exceptions.RequestException as e:
        print(f"❌ Request failed: {e}")
        return False

def test_upload_existing_file():
    """Test upload with an existing file if available"""
    print(f"\n📤 Testing upload with existing PDF file")

    # Try to find an existing file
    test_files = [
        "2024110410_wangyu (1).pdf",
        "README.md",
        "config.yaml",
        "main.py"
    ]

    for file_path in test_files:
        if Path(file_path).exists():
            print(f"Found existing file: {file_path}")

            with open(file_path, 'rb') as f:
                file_content = f.read()

            files = {
                'upload_file': (Path(file_path).name, io.BytesIO(file_content), 'application/octet-stream')
            }
            data = {
                'user_id': 'test_user_real_file'
            }

            try:
                response = requests.post(UPLOAD_ENDPOINT, files=files, data=data, timeout=30)

                print(f"Status Code: {response.status_code}")
                print(f"Response: {json.dumps(response.json(), indent=2)}")

                if response.status_code == 200:
                    result = response.json()
                    if result.get("status") == "success":
                        print("✅ Real file upload successful!")
                        return True
                    else:
                        print(f"❌ Upload failed: {result.get('message')}")
                        return False
                else:
                    print(f"❌ Upload failed with status code: {response.status_code}")
                    return False

            except requests.exceptions.RequestException as e:
                print(f"❌ Request failed: {e}")
                return False

    print("No existing files found for testing")
    return True

def main():
    """Run all tests"""
    print("🚀 Starting upload_minio endpoint tests")
    print("=" * 50)

    # Test server health first
    if not test_health_check():
        print("\n❌ Server is not running. Please start the server first:")
        print("   python main.py")
        return

    # Run all tests
    tests = [
        test_upload_with_user_id,
        test_upload_without_user_id,
        test_upload_no_file,
        test_upload_existing_file
    ]

    passed = 0
    total = len(tests)

    for test_func in tests:
        try:
            if test_func():
                passed += 1
        except Exception as e:
            print(f"❌ Test {test_func.__name__} failed with exception: {e}")

    print("\n" + "=" * 50)
    print(f"📊 Test Results: {passed}/{total} tests passed")

    if passed == total:
        print("🎉 All tests passed!")
    else:
        print("⚠️  Some tests failed. Check the output above for details.")

if __name__ == "__main__":
    main()
